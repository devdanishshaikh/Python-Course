a = 10
b = "20"
c = 3.14
# Check type of each
print("Before Data type conversion")
print("Type of a:", type(a))
print("type of b :", type(b))
print("Type of c :", type(c))

# Type casting
print("After Data type conversion")
a = str(a)
b = int(b)
c = int(c)

print("Type of a:", type(a))
print("type of b :", type(b))
print("Type of c :", type(c))